#!/usr/bin/env python3
"""Refresh platform-neutral compatibility IDs after adding Compose resources."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zlib

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / "composeApp/src/commonMain/composeResources"
OUTPUT = ROOT / "composeApp/src/commonMain/kotlin/com/menna/nabatan_7asena/resources/AppResources.kt"


def identifier(kind, name):
    return -(zlib.crc32(f"{kind}/{name}".encode()) & 0x7FFFFFFF or 1)


def main():
    resources = {}
    for kind in ("drawable", "font"):
        resources[kind] = sorted({p.stem for folder in RESOURCES.glob(f"{kind}*") for p in folder.iterdir() if p.is_file()})
    raw = {p.stem: p.relative_to(RESOURCES).as_posix() for p in (RESOURCES / "files").glob("*")
           if p.is_file() and re.fullmatch(r"[a-z][a-z0-9_]*", p.stem)}
    resources["raw"] = sorted(raw)
    resources["string"] = sorted({node.attrib["name"] for path in RESOURCES.glob("values*/strings.xml")
                                   for node in ET.parse(path).getroot() if node.tag == "string"})
    ids = [identifier(kind, name) for kind, names in resources.items() for name in names]
    if len(ids) != len(set(ids)):
        raise ValueError("Resource hash collision: assign a distinct resource name")
    lines = ["// Generated by tools/generate_resource_catalog.py; IDs are stable hashes of resource names.",
             "package com.menna.nabatan_7asena.resources", "", "import com.menna.nabatan.shared.generated.resources.*",
             "import org.jetbrains.compose.resources.*", "", "object AppResources {"]
    for kind, names in resources.items():
        lines += [f"    object {kind} {{"]
        lines += [f"        const val {name}: Int = {identifier(kind, name)}" for name in names]
        lines += ["    }"]
    lines += ["}", "", "object ResourceCatalog {"]
    for kind, resource_type in (("drawable", "DrawableResource"), ("font", "FontResource"), ("string", "StringResource")):
        lines += [f"    val {kind}s: Map<Int, {resource_type}> = mapOf("]
        lines += [f"        AppResources.{kind}.{name} to Res.{kind}.{name}," for name in resources[kind]]
        lines += ["    )"]
    lines += ["    val rawPaths = mapOf("]
    lines += [f'        AppResources.raw.{name} to "{raw[name]}",' for name in resources["raw"]]
    lines += ["    )", "    val drawableIdsByName = mapOf("]
    lines += [f'        "{name}" to AppResources.drawable.{name},' for name in resources["drawable"]]
    lines += ["    )", "}"]
    OUTPUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
